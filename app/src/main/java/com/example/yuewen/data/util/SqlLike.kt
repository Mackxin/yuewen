package com.example.yuewen.data.util

/**
 * 把用户输入的关键词拼成安全的 SQL `LIKE` 模式串（v2.3）。
 *
 * ## 为什么需要它
 *
 * 以前搜索是这么拼的：
 * ```
 * dao.search(category, "%$q%")
 * ```
 * `q` 直接塞进模式串里，**没有转义**。而 `LIKE` 里 `%` 和 `_` 是通配符：
 *
 * - 用户输入一个 `%` → 模式变成 `%%%` → **命中全库**，搜索看上去「失灵了」，
 *   返回的是一堆跟关键词毫无关系的文章；
 * - 输入一个 `_` → 变成 `%_%` → 匹配「至少一个字符」→ 同样几乎全中。
 *   中文输入法下按 `_` 很容易误触，这个 bug 用户碰到的概率不低。
 *
 * 解决办法是把 `\`、`%`、`_` 三个字符各加一层 `\` 转义，
 * 再让 SQL 那边声明 `ESCAPE '\'` 告诉 SQLite 「反斜杠是转义符」
 * （见 `ArticleDao.search` / `searchAll`）。
 *
 * ## 转义顺序很重要
 *
 * **必须先转义反斜杠**，再转义 `%` 和 `_`。反过来的话，
 * 刚给 `%` 加上的那个 `\` 会被后续的反斜杠转义步骤再翻一倍，
 * 结果模式串里变成一个「字面反斜杠 + 通配符」，还是搜不对。
 *
 * 这是个纯函数（不碰 android.*），所以能进离线回归测试。
 */
fun likePattern(query: String): String {
    val escaped = query
        .replace("\\", "\\\\")   // ① 先处理反斜杠本身，否则会污染后面两步
        .replace("%", "\\%")     // ② 通配符「任意多个字符」
        .replace("_", "\\_")     // ③ 通配符「任意一个字符」
    return "%$escaped%"
}

/**
 * SQL 里 `ESCAPE` 子句要用的转义符。
 *
 * 单独抽出来是为了让 DAO 的 SQL 和这里的转义逻辑**用同一个常量** ——
 * 哪天要换成 `!` 之类的字符，改一处就行，不会出现「转义用 `\`、SQL 声明用别的」这种对不上的情况。
 */
const val LIKE_ESCAPE_CHAR: Char = '\\'
